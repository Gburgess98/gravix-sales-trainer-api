/**
 * Generates the staging tenant-UUID repair SQL (forward + rollback) and the read-only verification SQL.
 *
 *   npx tsx scripts/generate-staging-tenant-uuid-repair.ts          # (re)write sql/staging/*.sql
 *   npx tsx scripts/validate-staging-tenant-uuids.ts                 # proves the committed files equal this output
 *
 * STAGING ONLY. Never run against production. The SQL is applied by an operator (Supabase SQL editor); this script
 * and the app never execute it. Both directions are transactional and idempotent.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { STAGING_TENANT_IDS as NEW, LEGACY_STAGING_TENANT_IDS as OLD, STAGING_FIXTURE_CALL_IDS } from "./staging-tenant-ids";

export const STRICT_PG = "^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$";

type Ids = { tmc: string; org: string; company: string; rep: string };
type Pair = [from: string, to: string];

const FILE_BASE = "20261105_repair_staging_tenant_uuids";

function header(direction: "forward" | "rollback"): string {
  const fwd = direction === "forward";
  return `-- ${FILE_BASE}${fwd ? "" : "_rollback"}.sql   (GENERATED by scripts/generate-staging-tenant-uuid-repair.ts — do not edit by hand)
--
-- STAGING ONLY. ${fwd
    ? "Replaces the malformed synthetic tenant ids (00000000-2711-0000-0000-…, version/variant nibble 0) with RFC-4122-valid ids (00000000-2711-4000-8000-…)."
    : "EMERGENCY ROLLBACK of the repair: restores the malformed 00000000-2711-0000-0000-… tenant ids. This re-introduces ids the API rejects; use only to return to the exact pre-repair state."}
-- Never apply to production. Applied by an operator in the Supabase SQL editor (staging project) — not by the app.
--
-- Properties
--   * One transaction: all or nothing.
--   * Idempotent: a second run finds nothing to move and succeeds without changes.
--   * Order: copy the tenant rows to their new ids (FK targets first) → repoint EVERY public uuid column and jsonb/text
--     value that references the old ids → prove no reference remains → delete the old tenant rows.
--   * Fails closed: aborts (rolls back) if the old org is not the 'Gravix Staging QA' fixture, or any reference remains.
--   * Excluded from the sweep on purpose: the tenant rows' own primary keys (handled by copy/delete) and
--     profiles.user_id (FKs auth.users; legacy synthetic auth users are retired by a separate optional file).
${fwd ? "--   * Rollback maps owner 0b→0c are NOT reversible (0b never had a rep row); see STAGING_ORG_IDENTITY_REPAIR.md.\n" : ""}`;
}

function esc(s: string) { return s.replace(/'/g, "''"); }

function body(from: Ids, to: Ids, sweep: Pair[], direction: "forward" | "rollback"): string {
  const fwd = direction === "forward";
  const sweepSql = sweep.map(([f, t]) => `    ('${f}'::uuid, '${t}'::uuid)`).join(",\n");
  const fromList = sweep.map(([f]) => `''${f}''`).join(", "); // quotes doubled: it sits inside a SQL string literal (format())
  const tenantTables = [
    // [table, pk column, extra columns to override in the copy]
    { t: "tmcs", pk: "id", over: (i: Ids) => `jsonb_build_object('id', '${i.tmc}')` , slug: true },
    { t: "orgs", pk: "id", over: (i: Ids) => `jsonb_build_object('id', '${i.org}')`, slug: false },
    { t: "companies", pk: "id", over: (i: Ids) => `jsonb_build_object('id', '${i.company}', 'tmc_id', '${i.tmc}')`, slug: true },
    { t: "reps", pk: "id", over: (i: Ids) => `jsonb_build_object('id', '${i.rep}', 'org_id', '${i.org}', 'company_id', '${i.company}')`, slug: false },
  ];
  const oldKey: Record<string, string> = { tmcs: from.tmc, orgs: from.org, companies: from.company, reps: from.rep };
  const newKey: Record<string, string> = { tmcs: to.tmc, orgs: to.org, companies: to.company, reps: to.rep };

  const copies = tenantTables.map((x) => {
    const slugFix = x.slug
      ? `-- the old row keeps its unique slug until deleted: park it so the copy can take the real one
update public.${x.t} set slug = slug || '--repair-' || substr(id::text, 25)
 where id = '${oldKey[x.t]}' and slug !~ '--repair-' and not exists (select 1 from public.${x.t} where id = '${newKey[x.t]}');
`
      : "";
    const slugOverride = x.slug ? ` || jsonb_build_object('slug', regexp_replace(t.slug, '--repair-.*$', ''))` : "";
    return `${slugFix}insert into public.${x.t}
select (jsonb_populate_record(null::public.${x.t}, to_jsonb(t) || ${x.over(to)}${slugOverride})).*
  from public.${x.t} t where t.id = '${oldKey[x.t]}'
on conflict (id) do nothing;
`;
  }).join("\n");

  return `begin;
set local lock_timeout = '15s';
set local statement_timeout = '120s';

-- 0. Guards ---------------------------------------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from public.orgs where id = '${from.org}')
     and not exists (select 1 from public.orgs where id = '${from.org}' and name = 'Gravix Staging QA') then
    raise exception 'refusing: org ${from.org} exists but is not the Gravix Staging QA fixture';
  end if;
  if not exists (select 1 from public.orgs where id in ('${from.org}', '${to.org}')) then
    raise exception 'refusing: neither the source nor the target fixture org exists (wrong project?)';
  end if;
end $$;

-- 1. Copy the tenant rows to their new ids (parents before children) ------------------------------------------------
${copies}
insert into public.org_settings
select (jsonb_populate_record(null::public.org_settings, to_jsonb(t) || jsonb_build_object('org_id', '${to.org}'))).*
  from public.org_settings t where t.org_id = '${from.org}'
on conflict (org_id) do nothing;

-- 2. Repoint every reference ----------------------------------------------------------------------------------------
do $$
declare
  m record; c record; n bigint; moved bigint := 0;
begin
  for m in select * from (values
${sweepSql}
  ) as v(old_id, new_id)
  loop
    -- uuid columns (every public base table), except the tenant rows' own keys and profiles.user_id
    for c in
      select cl.table_name, cl.column_name
        from information_schema.columns cl
        join information_schema.tables tb on tb.table_schema = cl.table_schema and tb.table_name = cl.table_name and tb.table_type = 'BASE TABLE'
       where cl.table_schema = 'public' and cl.data_type = 'uuid'
         and (cl.table_name, cl.column_name) not in (('tmcs','id'),('orgs','id'),('companies','id'),('reps','id'),('org_settings','org_id'),('profiles','user_id'))
    loop
      execute format('update public.%I set %I = $2 where %I = $1', c.table_name, c.column_name, c.column_name) using m.old_id, m.new_id;
      get diagnostics n = row_count; moved := moved + n;
    end loop;
    -- json/jsonb values that embed the id as text (e.g. sparring_sessions.meta)
    for c in
      select cl.table_name, cl.column_name
        from information_schema.columns cl
        join information_schema.tables tb on tb.table_schema = cl.table_schema and tb.table_name = cl.table_name and tb.table_type = 'BASE TABLE'
       where cl.table_schema = 'public' and cl.data_type = 'jsonb'
    loop
      execute format('update public.%I set %I = replace(%I::text, $1, $2)::jsonb where %I::text like ''%%'' || $1 || ''%%''', c.table_name, c.column_name, c.column_name, c.column_name) using m.old_id::text, m.new_id::text;
      get diagnostics n = row_count; moved := moved + n;
    end loop;
  end loop;
  raise notice 'repointed % reference(s)', moved;
end $$;

-- 3. Prove nothing still references the ids being retired ------------------------------------------------------------
do $$
declare c record; n bigint; bad text := '';
begin
  for c in
    select cl.table_name, cl.column_name, cl.data_type
      from information_schema.columns cl
      join information_schema.tables tb on tb.table_schema = cl.table_schema and tb.table_name = cl.table_name and tb.table_type = 'BASE TABLE'
     where cl.table_schema = 'public' and cl.data_type in ('uuid','jsonb','json','text','character varying')
       and (cl.table_name, cl.column_name) not in (('tmcs','id'),('orgs','id'),('companies','id'),('reps','id'),('org_settings','org_id'),('profiles','user_id'))
  loop
    execute format('select count(*) from public.%I where %I::text = any (array[${fromList}]) ${fwd ? "or (%L in (''jsonb'',''json'',''text'',''character varying'') and %I::text ~ ''00000000-27[0-9]{2}-0000-0000-'')" : ""}',
                   c.table_name, c.column_name${fwd ? ", c.data_type, c.column_name" : ""}) into n;
    if n > 0 then bad := bad || format(' %s.%s=%s', c.table_name, c.column_name, n); end if;
  end loop;
  if bad <> '' then raise exception 'repair aborted — references remain:%', bad; end if;
end $$;

-- 4. Retire the old tenant rows (children first) ---------------------------------------------------------------------
delete from public.org_settings where org_id = '${from.org}';
delete from public.reps         where id     = '${from.rep}';
delete from public.companies    where id     = '${from.company}';
delete from public.orgs         where id     = '${from.org}';
delete from public.tmcs         where id     = '${from.tmc}';

-- 5. Post-conditions ------------------------------------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from public.orgs      where id = '${to.org}')     then raise exception 'post-check failed: org ${to.org} missing'; end if;
  if not exists (select 1 from public.companies where id = '${to.company}') then raise exception 'post-check failed: company ${to.company} missing'; end if;
  if not exists (select 1 from public.tmcs      where id = '${to.tmc}')     then raise exception 'post-check failed: tmc ${to.tmc} missing'; end if;
end $$;

commit;
`;
}

export function buildRepairSql(direction: "forward" | "rollback"): string {
  if (direction === "forward") {
    const from: Ids = { tmc: OLD.tmcId, org: OLD.orgId, company: OLD.companyId, rep: OLD.ownerRepId };
    const to: Ids = { tmc: NEW.tmcId, org: NEW.orgId, company: NEW.companyId, rep: NEW.ownerRepId };
    const sweep: Pair[] = [
      [from.tmc, to.tmc], [from.org, to.org], [from.company, to.company], [from.rep, to.rep],
      [OLD.callOwnerId, to.rep], // calls/crm_activities were owned by 0b (never a rep row) → the one synthetic rep
      [OLD.staleCallIds[0], STAGING_FIXTURE_CALL_IDS.stubProofCallId], // dangling crm_activities.call_id → the valid twin
      [OLD.staleCallIds[1], STAGING_FIXTURE_CALL_IDS.v1FallbackCallId],
    ];
    return header("forward") + body(from, to, sweep, "forward");
  }
  const from: Ids = { tmc: NEW.tmcId, org: NEW.orgId, company: NEW.companyId, rep: NEW.ownerRepId };
  const to: Ids = { tmc: OLD.tmcId, org: OLD.orgId, company: OLD.companyId, rep: OLD.ownerRepId };
  const sweep: Pair[] = [[from.tmc, to.tmc], [from.org, to.org], [from.company, to.company], [from.rep, to.rep]];
  return header("rollback") + body(from, to, sweep, "rollback");
}

export function buildRetireLegacyAuthSql(): string {
  const ids = OLD.legacyAuthUserIds.map((i) => `'${i}'`).join(", ");
  return `-- ${FILE_BASE}_retire_legacy_auth_users.sql   (GENERATED — OPTIONAL, separate approval)
--
-- STAGING ONLY — never apply to production. The two hand-written auth users from before Day 273 (ids 00000000-2711-0000-0000-00000000000a/b) have
-- malformed ids that no API predicate accepts, and Auth cannot change a user's id. They cannot sign in usefully. This
-- removes them (public.profiles cascades via profiles_user_id_fkey) so no malformed id remains.
-- Run ONLY after ${FILE_BASE}.sql. Not reversible (passwords are not recoverable); the working QA logins are untouched.
begin;
do $$
begin
  if exists (select 1 from auth.users where id in (${ids}) and email not like '%@gravix.invalid') then
    raise exception 'refusing: a legacy id belongs to a non-synthetic email';
  end if;
end $$;
delete from public.profiles where user_id in (${ids});
delete from auth.users where id in (${ids}) and email like '%@gravix.invalid';
commit;
`;
}

export function buildVerifySql(): string {
  return `-- ${FILE_BASE}_verify.sql   (GENERATED, READ-ONLY)
-- Lists every public uuid column holding a value that fails the API's strict predicate. After the repair (and the optional
-- legacy-auth retirement) staging must return ZERO rows. Safe to run any time.
do $$
declare c record; n bigint; bad text := '';
begin
  for c in
    select cl.table_name, cl.column_name
      from information_schema.columns cl
      join information_schema.tables tb on tb.table_schema = cl.table_schema and tb.table_name = cl.table_name and tb.table_type = 'BASE TABLE'
     where cl.table_schema = 'public' and cl.data_type = 'uuid'
  loop
    execute format('select count(*) from public.%I where %I is not null and %I::text !~* %L', c.table_name, c.column_name, c.column_name, '${esc(STRICT_PG)}') into n;
    if n > 0 then bad := bad || format(E'\\n  %s.%s: %s row(s)', c.table_name, c.column_name, n); end if;
  end loop;
  if bad <> '' then raise notice 'columns failing the strict predicate:%', bad; else raise notice 'OK: every public uuid value passes the strict predicate'; end if;
end $$;
`;
}

export const REPAIR_FILES = {
  forward: `sql/staging/${FILE_BASE}.sql`,
  rollback: `sql/staging/${FILE_BASE}_rollback.sql`,
  retire: `sql/staging/${FILE_BASE}_retire_legacy_auth_users.sql`,
  verify: `sql/staging/${FILE_BASE}_verify.sql`,
} as const;

if (process.argv[1] && /generate-staging-tenant-uuid-repair/.test(process.argv[1])) {
  const root = join(__dirname, "..");
  writeFileSync(join(root, REPAIR_FILES.forward), buildRepairSql("forward"));
  writeFileSync(join(root, REPAIR_FILES.rollback), buildRepairSql("rollback"));
  writeFileSync(join(root, REPAIR_FILES.retire), buildRetireLegacyAuthSql());
  writeFileSync(join(root, REPAIR_FILES.verify), buildVerifySql());
  console.log("wrote", Object.values(REPAIR_FILES).join(", "));
}
